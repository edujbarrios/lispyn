"""Render an authentic and compact Hy notebook example for the README.

Full Hy source followed by real training/evaluation results and one chart.
Only consumes an executed notebook whose SHA-256 matches the source.
"""
from __future__ import annotations

import argparse
from hashlib import sha256
from pathlib import Path
import re

import nbformat

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "examples/quickstart.hy"
NOTEBOOK = ROOT / "example_generated_notebooks/quickstart_executed.ipynb"
FIGURE = ROOT / "example_generated_notebooks/assets/quickstart_training_curves.png"
README = ROOT / "README.md"
BEGIN = "<!-- QUICKSTART_EXECUTED:START -->"
END = "<!-- QUICKSTART_EXECUTED:END -->"
TICK = chr(96)


def _value(value):
    return "".join(value) if isinstance(value, list) else str(value)


def _fence(value, language):
    value = _value(value).rstrip("\n")
    run = max((len(match.group()) + 1 for match in re.finditer(TICK + "+", value)),
              default=3)
    delimiter = TICK * max(3, run)
    return f"{delimiter}{language}\n{value}\n{delimiter}"


def _single(items, what):
    if len(items) != 1:
        raise ValueError(f"Expected exactly one recorded {what}, found {len(items)}")
    return items[0]


def render(source=SOURCE, notebook_path=NOTEBOOK, figure=FIGURE):
    """Show complete Hy notebook syntax, then verified metrics and chart."""
    source, notebook_path, figure = map(Path, (source, notebook_path, figure))
    nb = nbformat.read(notebook_path, as_version=4)
    nbformat.validate(nb)
    digest = sha256(source.read_bytes()).hexdigest()
    provenance = nb.metadata.get("lispyn", {})
    if (provenance.get("source") != source.name or
            provenance.get("source_sha256") != digest):
        raise ValueError("Executed notebook provenance does not match the Hy source")
    if (not figure.is_file() or figure.stat().st_size < 3000 or
            not figure.read_bytes().startswith(b"\x89PNG\r\n\x1a\n")):
        raise ValueError("A real Matplotlib PNG from training is required")

    code_cells = [cell for cell in nb.cells if cell.cell_type == "code"]
    if not code_cells or any(cell.execution_count is None for cell in code_cells):
        raise ValueError("All notebook code cells must be executed")
    if any(output.output_type == "error" for cell in code_cells
           for output in cell.outputs):
        raise ValueError("Executed notebook contains an execution error")
    if "plot_history" not in code_cells[-1].source:
        raise ValueError("Final notebook cell must plot the training history")
    if not any("image/png" in output.get("data", {})
               for output in code_cells[-1].outputs):
        raise ValueError("Final plotting cell has no recorded PNG output")

    stdout = []
    markdown = []
    for cell in code_cells:
        for output in cell.outputs:
            if output.output_type == "stream":
                stdout.extend(_value(output.get("text", "")).splitlines())
            elif output.output_type in ("display_data", "execute_result"):
                data = output.get("data", {})
                if "text/markdown" in data:
                    markdown.append(_value(data["text/markdown"]).strip())
    split = _single([line for line in stdout if line.startswith("Samples:")],
                    "dataset split")
    epochs = _single([line for line in stdout if line.startswith("Completed epochs:")],
                     "completed training epoch count")
    training_report = _single(
        [value for value in markdown
         if value.startswith("# PyTorch baseline · recorded metrics")],
        "training report",
    )
    held_out = _single(
        [value for value in markdown if value.startswith("Held-out test accuracy:")],
        "held-out evaluation",
    )
    scores = _single(
        [value for value in markdown
         if value.startswith("### Recorded experiment scores")],
        "metric summary table",
    )

    return "\n".join([
        "### A complete notebook written in Hy/Lispyn", "",
        "This is the **complete, runnable source** of "
        "[`examples/quickstart.hy`](examples/quickstart.hy)."
        " The `md` macros become notebook Markdown cells; the remaining"
        " forms become ordinary Python code cells.", "",
        _fence(source.read_text(encoding="utf-8"), "hy"), "",
        "### Results from the executed notebook", "",
        "These values come directly from the "
        "[**executed Jupyter notebook**]"
        "(example_generated_notebooks/quickstart_executed.ipynb),"
        " not from manually written or simulated results.", "",
        "**Dataset and execution**", "",
        _fence(split + "\n" + epochs, "text"), "",
        "**Training report**", "",
        training_report, "",
        "**Held-out evaluation**", "",
        held_out, "",
        scores, "",
        "### Final graph — training vs. validation loss", "",
        "![Loss curves generated by Lispyn from real quickstart training]"
        "(example_generated_notebooks/assets/quickstart_training_curves.png)", "",
        "**[Open the full executed notebook]"
        "(example_generated_notebooks/quickstart_executed.ipynb)**"
        " · [View original Hy source](examples/quickstart.hy)", "",
        f"**Verified Hy source SHA-256:** {TICK}{digest}{TICK}.", "",
        "*The data are deliberately synthetic and small: this demonstrates"
        " the workflow, not model performance on a real research task.*", "",
    ]).rstrip() + "\n"


def rewrite(readme_path, section, *, check=False):
    readme_path = Path(readme_path)
    old = readme_path.read_text(encoding="utf-8")
    if old.count(BEGIN) != 1 or old.count(END) != 1:
        raise ValueError("Expected exactly one pair of README example markers")
    updated = (old.split(BEGIN, 1)[0] + BEGIN + "\n"
               + section.rstrip() + "\n" + END
               + old.split(END, 1)[1])
    if check and old != updated:
        raise ValueError("README snapshot is stale: regenerate from the executed notebook")
    if not check:
        readme_path.write_text(updated, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    section = render()
    rewrite(README, section, check=args.check)
    print(f"{'Verified' if args.check else 'Generated'} notebook showcase "
          f"from {NOTEBOOK.name}: {len(section)} characters")


if __name__ == "__main__":
    main()
